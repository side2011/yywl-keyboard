/**
 * Translate a key. In 'zh' mode returns the key as-is (identity).
 * Supports simple template interpolation: pass an object as the second arg.
 * e.g. t('用户选择了 {count} 个设备', { count: 3 })
 */
export function translate(key, lang, params) {
  let text;
  if (lang === 'zh') {
    text = key;
  } else {
    text = en[key] !== undefined ? en[key] : key;
  }
  if (params) {
    Object.keys(params).forEach(k => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k]);
    });
  }
  return text;
}
